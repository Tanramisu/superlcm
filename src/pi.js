// Pi writes each conversation as an append-only JSONL tree under ~/.pi/agent/sessions, so SuperLcm
// indexes the file itself, byte for byte (every branch, tool result and compaction entry included).
// A small Pi extension (written by setup) reports each finished turn and exposes SuperLcm's MCP tools.
import { closeSync, existsSync, openSync, readSync, realpathSync, statSync } from 'node:fs'
import { relative, isAbsolute, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { configFiles } from './harness.js'
const inside = (root, file) => { const rel = relative(root, file); return rel && rel !== '..' && !rel.startsWith('..' + sep) && !isAbsolute(rel) }
export const piSessionKey = id => 'pi-' + id
function head(file) {
  const fd = openSync(file, 'r')
  try { const buf = Buffer.alloc(Math.min(statSync(file).size, 64 * 1024)); const n = readSync(fd, buf, 0, buf.length, 0); return JSON.parse(buf.subarray(0, n).toString('utf8').split('\n')[0]) } finally { closeSync(fd) }
}
function sessionName(file) {
  // The latest session_info name, if the user named the conversation in Pi.
  let name = null
  try { for (const line of require_lines(file)) { if (line.includes('"session_info"')) { const x = JSON.parse(line); if (x.type === 'session_info' && typeof x.name === 'string') name = x.name } } } catch {}
  return name
}
function require_lines(file) {
  const size = statSync(file).size, fd = openSync(file, 'r')
  try { const buf = Buffer.alloc(Math.min(size, 32 * 1024 * 1024)); const n = readSync(fd, buf, 0, buf.length, 0); return buf.subarray(0, n).toString('utf8').split('\n') } finally { closeSync(fd) }
}
export function capturePi(store, { session_id: id, session_file: path }, { env = process.env, automatic = false } = {}) {
  if (typeof id !== 'string' || !/^[\w.-]{1,190}$/.test(id)) throw new Error('Invalid Pi session id')
  const session = piSessionKey(id)
  if (automatic && store.isDeleted(session)) return { session, skipped: 'deleted' }
  if (typeof path !== 'string' || !existsSync(path)) return { session, skipped: 'not_written_yet' } // Pi writes the file after the first answer
  const root = realpathSync(configFiles('pi', env).transcripts), file = realpathSync(path)
  if (!inside(root, file)) throw new Error('Pi session file is outside the Pi sessions folder')
  const header = head(file)
  if (header?.type !== 'session' || header.id !== id) throw new Error('Pi session file does not belong to this session')
  const result = store.ingest(session, file,'jsonl',{automatic})
  if(result.skipped)return result
  const name = sessionName(file)
  store.setMetadata(session, { harness: 'pi', externalId: id, name: name || null, nameSource: name ? 'native' : 'derived' })
  return { ...result, session }
}
// The extension Pi auto-discovers. Compaction takeover is separately opt-in.
export function piExtension({ node, script, home }) {
  const q = JSON.stringify
  return `// SuperLcm for Pi — generated by SuperLcm setup; edits are overwritten on the next setup.
// Saves every finished turn to SuperLcm and gives Pi's AI the SuperLcm tools (lcm_find, lcm_read, ...).
import { spawn } from "node:child_process";
import { piMcpClient } from ${q(fileURLToPath(new URL('./pi-mcp-client.js', import.meta.url)))};
import { registerPiCompaction } from ${q(fileURLToPath(new URL('./pi-runtime.js', import.meta.url)))};
const NODE = ${q(node)}, CLI = ${q(script)}, HOME = ${q(home)};
function report(ctx, event) {
  const sessionId = ctx.sessionManager.getSessionId(), sessionFile = ctx.sessionManager.getSessionFile();
  if (!sessionId) return;
  const child = spawn(NODE, [CLI, "pi-hook", "--home", HOME], { stdio: ["pipe", "ignore", "ignore"], detached: true, windowsHide: true });
  child.on("error", () => {});
  child.stdin.on("error", () => {});
  child.stdin.end(JSON.stringify({ hook_event_name: event, session_id: sessionId, session_file: sessionFile }));
  child.unref();
}
// Same report, but waits for SuperLcm's answer: a short note for the AI this turn (对话模型生成), or nothing.
function ask(ctx, event) {
  const sessionId = ctx.sessionManager.getSessionId(), sessionFile = ctx.sessionManager.getSessionFile();
  if (!sessionId) return Promise.resolve({});
  return new Promise(resolve => {
    const child = spawn(NODE, [CLI, "pi-hook", "--home", HOME], { stdio: ["pipe", "pipe", "ignore"], windowsHide: true });
    child.stdout.setEncoding("utf8");
    let out = "";
    const timer = setTimeout(() => { try { child.kill(); } catch {} resolve({}); }, 10000);
    child.stdout.on("data", d => { out += d; });
    child.on("error", () => { clearTimeout(timer); resolve({}); });
    child.on("close", () => { clearTimeout(timer); try { resolve(JSON.parse(out) || {}); } catch { resolve({}); } });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify({ hook_event_name: event, session_id: sessionId, session_file: sessionFile }));
  });
}
export default function (pi) {
  registerPiCompaction(pi, { node: NODE, script: CLI, home: HOME });
  let client = null, connecting = null, generation = 0; const registered = new Set();
  async function connect() {
    if(connecting)return connecting;
    if(client?.alive)return client;
    const epoch=generation;
    const candidate=piMcpClient({node:NODE,script:CLI,home:HOME,onDead:()=>{if(client===candidate)client=null;}});
    client=candidate;
    const pending=(async()=>{
      try{
        await candidate.call("initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "pi", version: "superlcm-extension" } });
        candidate.notify("notifications/initialized", {});
        const {tools}=await candidate.call("tools/list", {});
        if(epoch!==generation||!candidate.alive)throw Error("SuperLcm MCP connection changed");
        for(const tool of tools){
          if(registered.has(tool.name))continue;
          pi.registerTool({name:tool.name,label:tool.name,description:tool.description||tool.name,parameters:tool.inputSchema||{type:"object",properties:{}},
            async execute(_id,params,signal){
              const active=await connect();
              const result=await active.call("tools/call",{name:tool.name,arguments:params||{}},signal);
              return {content:(result.content||[]).filter(c=>c.type==="text").map(c=>({type:"text",text:c.text})),details:{}};
            }});
          registered.add(tool.name);
        }
        return candidate;
      }catch(error){candidate.close();throw error}
    })();
    connecting=pending;
    try{return await pending}finally{if(connecting===pending)connecting=null;}
  }
  pi.on("session_start",async(_event,ctx)=>{
    report(ctx,"session_start");
    try{await connect()}catch(error){ctx.ui?.notify?.("SuperLcm tools unavailable: "+error.message,"warning");}
  });
  pi.on("before_agent_start", async (_event, ctx) => {
    const reply = await ask(ctx, "before_agent_start");
    if (reply.context) return { message: { customType: "superlcm", content: reply.context, display: false } };
  });
  for (const event of ["turn_end", "agent_settled", "session_compact"]) pi.on(event, async (_event, ctx) => report(ctx, event));
  pi.on("session_shutdown", async (_event, ctx) => { report(ctx, "session_shutdown"); generation++; try { client?.close(); } catch {} client = null; connecting = null; });
  pi.registerCommand("superlcm-status", { description: "Show whether SuperLcm is loaded", handler: async (_args, ctx) => {
    const tools = pi.getActiveTools().filter(n => n.startsWith("lcm_"));
    ctx.ui.notify("SuperLcm tools: " + (tools.join(",") || "none"), "info");
  } });
}
`
}
